CREATE SCHEMA SURVDEMO;
GO

CREATE TABLE SURVDEMO.POLICY
(
    POLICY_ID             char(12) COLLATE Latin1_General_100_BIN2 NOT NULL,
    INSURED_ID            char(10) COLLATE Latin1_General_100_BIN2 NOT NULL,
    PRODUCT_CODE          char(6) COLLATE Latin1_General_100_BIN2 NOT NULL,
    BASE_MONTHLY_BENEFIT  decimal(11,2) NOT NULL,
    FAMILY_MAX_PCT        decimal(5,2) NOT NULL
        CONSTRAINT DF_POLICY_FAMILY_MAX_PCT DEFAULT (100.00),
    STATUS                char(1) COLLATE Latin1_General_100_BIN2 NOT NULL
        CONSTRAINT DF_POLICY_STATUS DEFAULT ('A'),
    EFFECTIVE_DATE        date NOT NULL,
    TERMINATION_DATE      date NULL,
    CREATED_TS            datetime2(6) NOT NULL
        CONSTRAINT DF_POLICY_CREATED_TS DEFAULT (SYSUTCDATETIME()),
    UPDATED_TS            datetime2(6) NOT NULL
        CONSTRAINT DF_POLICY_UPDATED_TS DEFAULT (SYSUTCDATETIME()),
    CONSTRAINT PK_POLICY PRIMARY KEY (POLICY_ID),
    CONSTRAINT CK_POLICY_STATUS CHECK (STATUS IN ('A', 'L', 'T')),
    CONSTRAINT CK_POLICY_FAMILY_MAX CHECK (FAMILY_MAX_PCT > 0 AND FAMILY_MAX_PCT <= 100.00)
);

CREATE TABLE SURVDEMO.SURVIVOR_CLAIM
(
    CLAIM_ID          char(12) COLLATE Latin1_General_100_BIN2 NOT NULL,
    POLICY_ID         char(12) COLLATE Latin1_General_100_BIN2 NOT NULL,
    DATE_OF_DEATH     date NOT NULL,
    CLAIM_STATUS      char(1) COLLATE Latin1_General_100_BIN2 NOT NULL,
    APPROVED_DATE     date NULL,
    VERSION_NO        int NOT NULL CONSTRAINT DF_CLAIM_VERSION_NO DEFAULT (1),
    UPDATED_TS        datetime2(6) NOT NULL
        CONSTRAINT DF_CLAIM_UPDATED_TS DEFAULT (SYSUTCDATETIME()),
    CONSTRAINT PK_SURVIVOR_CLAIM PRIMARY KEY (CLAIM_ID),
    CONSTRAINT FK_CLAIM_POLICY FOREIGN KEY (POLICY_ID) REFERENCES SURVDEMO.POLICY (POLICY_ID),
    CONSTRAINT CK_CLAIM_STATUS CHECK (CLAIM_STATUS IN ('P', 'A', 'D', 'C'))
);

CREATE TABLE SURVDEMO.BENEFICIARY
(
    BENEFICIARY_ID    char(10) COLLATE Latin1_General_100_BIN2 NOT NULL,
    BENEFICIARY_NAME  nvarchar(60) NOT NULL,
    DATE_OF_BIRTH     date NOT NULL,
    RELATIONSHIP      char(3) COLLATE Latin1_General_100_BIN2 NOT NULL,
    STATUS            char(1) COLLATE Latin1_General_100_BIN2 NOT NULL
        CONSTRAINT DF_BENEFICIARY_STATUS DEFAULT ('A'),
    CREATED_TS        datetime2(6) NOT NULL
        CONSTRAINT DF_BENEFICIARY_CREATED_TS DEFAULT (SYSUTCDATETIME()),
    UPDATED_TS        datetime2(6) NOT NULL
        CONSTRAINT DF_BENEFICIARY_UPDATED_TS DEFAULT (SYSUTCDATETIME()),
    CONSTRAINT PK_BENEFICIARY PRIMARY KEY (BENEFICIARY_ID),
    CONSTRAINT CK_BENEFICIARY_RELATIONSHIP CHECK (RELATIONSHIP IN ('SPS', 'CHD', 'DEP')),
    CONSTRAINT CK_BENEFICIARY_STATUS CHECK (STATUS IN ('A', 'I', 'D'))
);

CREATE TABLE SURVDEMO.SURVIVOR_ENTITLEMENT
(
    CLAIM_ID            char(12) COLLATE Latin1_General_100_BIN2 NOT NULL,
    BENEFICIARY_ID      char(10) COLLATE Latin1_General_100_BIN2 NOT NULL,
    BENEFIT_PCT         decimal(5,2) NOT NULL,
    OTHER_INCOME_OFFSET decimal(11,2) NOT NULL
        CONSTRAINT DF_ENTITLEMENT_OFFSET DEFAULT (0),
    START_DATE          date NOT NULL,
    END_DATE            date NULL,
    STATUS              char(1) COLLATE Latin1_General_100_BIN2 NOT NULL,
    MONTHLY_AMOUNT      decimal(11,2) NOT NULL
        CONSTRAINT DF_ENTITLEMENT_MONTHLY_AMOUNT DEFAULT (0),
    TOTAL_PAID          decimal(13,2) NOT NULL
        CONSTRAINT DF_ENTITLEMENT_TOTAL_PAID DEFAULT (0),
    VERSION_NO          int NOT NULL CONSTRAINT DF_ENTITLEMENT_VERSION_NO DEFAULT (1),
    UPDATED_TS          datetime2(6) NOT NULL
        CONSTRAINT DF_ENTITLEMENT_UPDATED_TS DEFAULT (SYSUTCDATETIME()),
    CONSTRAINT PK_SURVIVOR_ENTITLEMENT PRIMARY KEY (CLAIM_ID, BENEFICIARY_ID),
    CONSTRAINT FK_ENTITLEMENT_CLAIM FOREIGN KEY (CLAIM_ID)
        REFERENCES SURVDEMO.SURVIVOR_CLAIM (CLAIM_ID),
    CONSTRAINT FK_ENTITLEMENT_BENEFICIARY FOREIGN KEY (BENEFICIARY_ID)
        REFERENCES SURVDEMO.BENEFICIARY (BENEFICIARY_ID),
    CONSTRAINT CK_ENTITLEMENT_PCT CHECK (BENEFIT_PCT > 0 AND BENEFIT_PCT <= 100.00),
    CONSTRAINT CK_ENTITLEMENT_OFFSET CHECK (OTHER_INCOME_OFFSET >= 0),
    CONSTRAINT CK_ENTITLEMENT_STATUS CHECK (STATUS IN ('A', 'S', 'E', 'C'))
);

CREATE TABLE SURVDEMO.CALC_RUN
(
    RUN_ID             char(12) COLLATE Latin1_General_100_BIN2 NOT NULL,
    CALC_DATE          date NOT NULL,
    BENEFIT_MONTH      date NOT NULL,
    PAYMENT_COUNT      int NOT NULL CONSTRAINT DF_CALC_RUN_PAYMENT_COUNT DEFAULT (0),
    PAYMENT_TOTAL      decimal(13,2) NOT NULL CONSTRAINT DF_CALC_RUN_PAYMENT_TOTAL DEFAULT (0),
    EXCEPTION_COUNT    int NOT NULL CONSTRAINT DF_CALC_RUN_EXCEPTION_COUNT DEFAULT (0),
    STATUS             char(1) COLLATE Latin1_General_100_BIN2 NOT NULL,
    CREATED_TS         datetime2(6) NOT NULL
        CONSTRAINT DF_CALC_RUN_CREATED_TS DEFAULT (SYSUTCDATETIME()),
    COMPLETED_TS       datetime2(6) NULL,
    CONSTRAINT PK_CALC_RUN PRIMARY KEY (RUN_ID),
    CONSTRAINT CK_CALC_RUN_STATUS CHECK (STATUS IN ('R', 'C', 'F'))
);

CREATE TABLE SURVDEMO.BENEFIT_PAYMENT
(
    PAYMENT_ID         char(16) COLLATE Latin1_General_100_BIN2 NOT NULL,
    RUN_ID             char(12) COLLATE Latin1_General_100_BIN2 NOT NULL,
    CLAIM_ID           char(12) COLLATE Latin1_General_100_BIN2 NOT NULL,
    BENEFICIARY_ID     char(10) COLLATE Latin1_General_100_BIN2 NOT NULL,
    BENEFIT_MONTH      date NOT NULL,
    GROSS_AMOUNT       decimal(11,2) NOT NULL,
    OFFSET_AMOUNT      decimal(11,2) NOT NULL,
    NET_AMOUNT         decimal(11,2) NOT NULL,
    STATUS             char(1) COLLATE Latin1_General_100_BIN2 NOT NULL,
    CREATED_TS         datetime2(6) NOT NULL
        CONSTRAINT DF_BENEFIT_PAYMENT_CREATED_TS DEFAULT (SYSUTCDATETIME()),
    CONSTRAINT PK_BENEFIT_PAYMENT PRIMARY KEY (PAYMENT_ID),
    CONSTRAINT FK_PAYMENT_RUN FOREIGN KEY (RUN_ID) REFERENCES SURVDEMO.CALC_RUN (RUN_ID),
    CONSTRAINT FK_PAYMENT_ENTITLEMENT FOREIGN KEY (CLAIM_ID, BENEFICIARY_ID)
        REFERENCES SURVDEMO.SURVIVOR_ENTITLEMENT (CLAIM_ID, BENEFICIARY_ID),
    CONSTRAINT CK_PAYMENT_STATUS CHECK (STATUS IN ('R', 'C', 'V'))
);

CREATE UNIQUE INDEX UX_BENEFIT_PAYMENT_PERIOD
    ON SURVDEMO.BENEFIT_PAYMENT (CLAIM_ID, BENEFICIARY_ID, BENEFIT_MONTH);

CREATE TABLE SURVDEMO.CALC_EXCEPTION
(
    EXCEPTION_ID       bigint IDENTITY(1,1) NOT NULL,
    RUN_ID             char(12) COLLATE Latin1_General_100_BIN2 NOT NULL,
    CLAIM_ID           char(12) COLLATE Latin1_General_100_BIN2 NULL,
    BENEFICIARY_ID     char(10) COLLATE Latin1_General_100_BIN2 NULL,
    EXCEPTION_CODE     char(2) COLLATE Latin1_General_100_BIN2 NOT NULL,
    EXPECTED_AMOUNT    decimal(11,2) NULL,
    ACTUAL_AMOUNT      decimal(11,2) NULL,
    STATUS             char(1) COLLATE Latin1_General_100_BIN2 NOT NULL
        CONSTRAINT DF_CALC_EXCEPTION_STATUS DEFAULT ('O'),
    CREATED_TS         datetime2(6) NOT NULL
        CONSTRAINT DF_CALC_EXCEPTION_CREATED_TS DEFAULT (SYSUTCDATETIME()),
    CONSTRAINT PK_CALC_EXCEPTION PRIMARY KEY (EXCEPTION_ID),
    CONSTRAINT FK_EXCEPTION_RUN FOREIGN KEY (RUN_ID) REFERENCES SURVDEMO.CALC_RUN (RUN_ID),
    CONSTRAINT CK_CALC_EXCEPTION_STATUS CHECK (STATUS IN ('O', 'R', 'C'))
);

CREATE INDEX IX_CLAIM_POLICY_STATUS
    ON SURVDEMO.SURVIVOR_CLAIM (POLICY_ID, CLAIM_STATUS, CLAIM_ID);

CREATE INDEX IX_ENTITLEMENT_CALC
    ON SURVDEMO.SURVIVOR_ENTITLEMENT (STATUS, START_DATE, END_DATE, CLAIM_ID, BENEFICIARY_ID);

CREATE INDEX IX_CALC_EXCEPTION_RUN
    ON SURVDEMO.CALC_EXCEPTION (RUN_ID, EXCEPTION_CODE);